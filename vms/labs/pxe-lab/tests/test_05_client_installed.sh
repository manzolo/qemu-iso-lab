#!/usr/bin/env bash
# Exercise 5 — the client was installed over the network and now boots its own disk.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_common.sh"
echo ""; echo "${BOLD}Exercise 5 — the client, installed over the network${RESET}"; echo ""

release=$(on pxe-lab-client cat /etc/os-release)
assert_contains "Debian 13 runs on the client" "$release" 'VERSION_ID="13"'
assert_contains "with the hostname the menu gave it" "$(on pxe-lab-client hostname)" "^pxe-lab-client$"
assert "the installer's logs are on its disk" on pxe-lab-client sudo test -s /var/log/installer/syslog
assert "it booted from its own disk (root on vda)" on pxe-lab-client sh -c 'findmnt -no SOURCE / | grep -q "^/dev/vda"'
assert "the answers on the server are the ones vmctl wrote" on pxe-lab-server grep -q 'Debian preseed generated by vmctl' /srv/pxe/www/debian/preseed.cfg
assert "the late script came over HTTP too" on pxe-lab-server test -s /srv/pxe/www/debian/late_command.sh
sudoers=$(on pxe-lab-client sudo -n true && echo ok)
assert_contains "the late script's sudo rule works" "$sudoers" "^ok$"

report_results "Exercise 5"

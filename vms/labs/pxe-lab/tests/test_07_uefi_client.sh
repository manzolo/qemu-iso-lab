#!/usr/bin/env bash
# Exercise 7 — a UEFI client takes the other road: option 93, Debian's shim and GRUB over TFTP, the installer over HTTP.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_common.sh"
echo ""; echo "${BOLD}Exercise 7 — UEFI: the same network, another boot loader${RESET}"; echo ""

conf=$(on pxe-lab-server cat /etc/dnsmasq.d/pxe-lab.conf)
assert_contains "dnsmasq tags UEFI clients by option 93" "$conf" "dhcp-match=set:efi64,option:client-arch,7"
assert_contains "and hands them the shim, not pxelinux" "$conf" "dhcp-boot=tag:!ipxe,tag:efi64,debian-installer/amd64/bootnetx64\.efi"
assert_contains "BIOS clients still get pxelinux" "$conf" "dhcp-boot=tag:!ipxe,tag:!efi64,lpxelinux\.0"
for file in bootnetx64.efi grubx64.efi grub/grub.cfg grub/x86_64-efi/http.mod grub/x86_64-efi/regexp.mod; do
    assert "$file is in the TFTP root" on pxe-lab-server test -s /srv/pxe/tftp/debian-installer/amd64/$file
done
assert "grubx64.efi also at the root, where the shim asks for it" on pxe-lab-server cmp -s /srv/pxe/tftp/grubx64.efi /srv/pxe/tftp/debian-installer/amd64/grubx64.efi
menu=$(on pxe-lab-client-efi curl -s tftp://172.20.9.1/debian-installer/amd64/grub/grub.cfg)
assert_contains "GRUB's menu comes over TFTP" "$menu" "menuentry 'Install Debian \(automated, preseed, UEFI\)'"
assert_contains "it loads the installer over HTTP" "$menu" "linux \(http,172\.20\.9\.1\)/debian/linux"
assert_contains "with BOOTIF built from the netboot MAC" "$menu" "BOOTIF=01-\\\$m1-"
assert_contains "and the UEFI client's own answers" "$menu" "url=http://172\.20\.9\.1/debian-efi/preseed\.cfg"

assert "the client booted UEFI" on pxe-lab-client-efi test -d /sys/firmware/efi
assert_contains "with the hostname GRUB's menu gave it" "$(on pxe-lab-client-efi hostname)" "^pxe-lab-client-efi$"
assert_contains "the installer wrote its boot entry" "$(on pxe-lab-client-efi sudo efibootmgr)" "debian"
assert "and the removable path, in case the entry is lost" on pxe-lab-client-efi sudo test -s /boot/efi/EFI/BOOT/BOOTX64.EFI
mac=$(on pxe-lab-client-efi sh -c 'ip -o -4 addr | awk "/172\\.20\\.9\\./ {print \$2}" | xargs -I{} cat /sys/class/net/{}/address')
bootif=$(on pxe-lab-client-efi sudo grep -o 'BOOTIF=[^ ]*' /var/log/installer/syslog | head -1)
assert_contains "the installer was told the segment NIC" "$bootif" "BOOTIF=01-${mac//:/-}"
assert "its answers are the ones vmctl wrote into debian-efi/" on pxe-lab-server grep -q 'Debian preseed generated by vmctl' /srv/pxe/www/debian-efi/preseed.cfg

report_results "Exercise 7"
